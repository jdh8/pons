#!/bin/sh
# ab-escape-values-lane.sh — the values double of their escape after our
# business redouble (`1NT (X) XX (2x) .. X`), which ab-escape-double-4cell.sh
# could not isolate.
#
# That run's `novalues` arm diverged on 0 boards in every cell: opener's
# leave-in is `stack || (XX && values)`, and the stack double also fires in
# the redoubled lane, so with `penalize_escape_stack` on the values knob is
# shadowed (the floor doubles there anyway and opener still sits).  Its
# `nostack` arm read a plain-DD loss in all four cells and goes default-off
# (jdh8, 2026-10-18), so this run measures the values knob against that new
# default: `nostack` (control, already on disk) vs `noboth`, same deals.
#
# PRE-REGISTERED (2026-10-18, before any number is read).  Same results dir,
# SEED_BASE and BOARDS=2400000 as ab-escape-double-4cell.sh, so the `nostack`
# arms and the density are reused; VULS="none both ns ew".
#   - The values double (on) stands in a cell whose nostack-vs-noboth plain
#     DD reads non-inferior or better.
#   - Plain-DD loss in all four cells → proposed to jdh8 for default-off,
#     flagged, not applied.
#   - Any other reading is flagged for jdh8's decision.
# No sd-lead: ab-dump-sd cannot disclose the ON arm's stack knob, so its
# blind leader would read the control wrong.  It was a tie-break only.
#
#   SKIP_BUILD=1 JOBS=96 BOARDS=2400000 VULS="none both ns ew" DDSS_THREADS=96 \
#       BBA_GEN=$HOME/.local/opt/glibc-2.36/bba-gen \
#       scripts/idle-run.sh scripts/ab-escape-values-lane.sh ab-results/escape-double-4cell
#
# SKIP_BUILD=1 is required: the control arms were generated by the 72f838f1
# binaries, and the new arm must come from the same ones.  Those binaries
# predate the stack flip, so `--no-ns-penalize-escape-stack` below is their
# spelling; today's `bba-gen` has the stack off by default.
#
# Read 2026-10-18 (verdicts in docs/research-method-review.md §6): plain DD
# loss in all four cells (−0.0005..−0.0006), PD a wash.
R=${1:?usage: ab-escape-values-lane.sh RESULTS_DIR}
. "$(dirname "$0")/ab-lib.sh"

SEED_BASE=$(seed_for escape-double)
log "=== escape-values-lane SEED_BASE=$SEED_BASE sha=$SHA shards=$SHARDS x $PER_SHARD bd/arm/vul"

for v in $VULS; do
    arm noboth "$v" --filter-1nt --wide-1nt \
        --no-ns-penalize-escape-stack --no-ns-penalize-escape-values
    DENSITY=$(density_of "$R/default-$v")
    diffpair nostack noboth "$v"
done
log "escape-values-lane done"
